    private void loadFeedbacks(String keyword) {
        javax.swing.table.DefaultTableModel m =
                (javax.swing.table.DefaultTableModel) tblFeedbacks.getModel();
        m.setRowCount(0);
        java.util.List<String[]> rows = svc.getFeedbackRows(keyword);
        for (String[] r : rows) m.addRow(r);
        lblCount.setText(rows.size() + " record(s)");
    }


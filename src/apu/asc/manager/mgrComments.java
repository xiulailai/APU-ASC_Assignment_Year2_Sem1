    private void loadComments(String keyword) {
        javax.swing.table.DefaultTableModel m =
                (javax.swing.table.DefaultTableModel) tblComments.getModel();
        m.setRowCount(0);
        java.util.List<String[]> rows = svc.getCommentRows(keyword);
        for (String[] r : rows) m.addRow(r);
        lblCount.setText(rows.size() + " record(s)");
    }

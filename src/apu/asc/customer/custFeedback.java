    private void cbApptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbApptActionPerformed
        int idx = cbAppt.getSelectedIndex();
        if (idx < 0 || idx >= apptIds.size()) {
            jTextArea1.setText("");
            lblTarget.setText("Submitted by:");
            return;
        }
        String apptId = apptIds.get(idx);
        java.util.List<apu.asc.staff.Feedback> feedbacks = svc.getFeedbacksForAppointment(apptId);
        if (feedbacks.isEmpty()) {
            jTextArea1.setText("No feedback for this appointment.");
            lblTarget.setText("Submitted by: –");
        } else {
            apu.asc.staff.Feedback f = feedbacks.get(0);
            jTextArea1.setText(f.getFeedbackText());
            apu.asc.staff.Technician tech = svc.getTechnicianById (f.getTechnicianId());
            String name = tech != null ? tech.getName() : f.getTechnicianId();
            lblTarget.setText("Submitted by: " + name + " [" + f.getTechnicianId() + "]");
        }
    }//GEN-LAST:event_cbApptActionPerformed

    private void refreshAppointments() {
        cbAppt.removeAllItems();
        apptIds.clear();
        java.util.List<String[]> labels = svc.getAppointmentLabels();
        if (labels.isEmpty()) {
            cbAppt.addItem("No appointments found");
        } else {
            for (String[] pair : labels) {
                apptIds.add(pair[0]);
                cbAppt.addItem(pair[1]);
            }
        }
        if (cbAppt.getItemCount() > 0) cbAppt.setSelectedIndex(0);
    }


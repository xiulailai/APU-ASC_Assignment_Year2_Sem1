    private void refreshAppointments() {
        cbAppt.removeAllItems();
        apptIds.clear();
        java.util.List<String[]> labels = svc.getAppointmentLabels();
        if (labels.isEmpty()) {
            cbAppt.addItem("No appointments found");
            btnSubmit.setEnabled(false);
        } else {
            for (String[] pair : labels) {
                apptIds.add(pair[0]);
                cbAppt.addItem(pair[1]);
            }
            btnSubmit.setEnabled(true);
        }
        refreshTargets();
        refreshPastComments();
    }

    private void refreshTargets() {
        cbTarget.removeAllItems();
        targetIds.clear();
        int idx = cbAppt.getSelectedIndex();
        if (idx < 0 || idx >= apptIds.size()) return;
        String apptId = apptIds.get(idx);
        for (String[] t : svc.getCommentTargets(apptId)) {
            targetIds.add(t[0]);
            boolean already = svc.hasCommented(apptId, t[0]);
            cbTarget.addItem(t[1] + (already ? " [Commented]" : ""));
        }
    }

    private void refreshPastComments() {
        listModel.clear();
        int idx = cbAppt.getSelectedIndex();
        if (idx < 0 || idx >= apptIds.size()) return;
        String apptId = apptIds.get(idx);
        java.util.List<apu.asc.staff.Comment> comments = svc.getCommentsForAppointment(apptId);
        if (comments.isEmpty()) {
            listModel.addElement("No comments submitted for this appointment.");
        } else {
            for (apu.asc.staff.Comment c : comments) {
                listModel.addElement("[" + c.getTargetUserId() + "]  " + c.getCommentText());
            }
        }
    }

    private void submitComment() {
        lblStatus.setForeground(java.awt.Color.RED);
        int apptIdx   = cbAppt.getSelectedIndex();
        int targetIdx = cbTarget.getSelectedIndex();
        if (apptIdx < 0 || apptIdx >= apptIds.size()) {
            lblStatus.setText("No appointment selected.");
            return;
        }
        if (targetIdx < 0 || targetIdx >= targetIds.size()) {
            lblStatus.setText("No target selected.");
            return;
        }
        String apptId   = apptIds.get(apptIdx);
        String targetId = targetIds.get(targetIdx);
        String text     = taComment.getText().trim();
        try {
            String result = svc.addComment(apptId, targetId, text);
            boolean ok = result.startsWith("SUCCESS");
            lblStatus.setForeground(ok ? new java.awt.Color(0, 128, 96) : java.awt.Color.RED);
            lblStatus.setText(result.replace("SUCCESS: ", "").replace("ERROR: ", ""));
            if (ok) {
                taComment.setText("");
                refreshTargets();
                refreshPastComments();
            }
        } catch (java.io.IOException e) {
            lblStatus.setText("Error: " + e.getMessage());
        }
    }


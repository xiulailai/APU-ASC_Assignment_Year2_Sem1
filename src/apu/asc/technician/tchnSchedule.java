    private void setupTable() {
        tableModel = new javax.swing.table.DefaultTableModel(
                new String[]{"Date", "Day", "Time", "Service",
                             "Duration", "Customer", "Phone", "Status"}, 0) {
            public boolean isCellEditable(int r, int c) { return false; }
        };
        tblSchedule.setModel(tableModel);
 
        // Column widths
        tblSchedule.getColumnModel().getColumn(0).setPreferredWidth(90);  // Date
        tblSchedule.getColumnModel().getColumn(1).setPreferredWidth(70);  // Day
        tblSchedule.getColumnModel().getColumn(2).setPreferredWidth(55);  // Time
        tblSchedule.getColumnModel().getColumn(3).setPreferredWidth(110); // Service
        tblSchedule.getColumnModel().getColumn(4).setPreferredWidth(65);  // Duration
        tblSchedule.getColumnModel().getColumn(5).setPreferredWidth(110); // Customer
        tblSchedule.getColumnModel().getColumn(6).setPreferredWidth(100); // Phone
        tblSchedule.getColumnModel().getColumn(7).setPreferredWidth(75);  // Status
 
        // Colour-code Status column
        tblSchedule.getColumnModel().getColumn(7).setCellRenderer(
                new javax.swing.table.DefaultTableCellRenderer() {
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable t, Object v,
                    boolean sel, boolean foc, int row, int col) {
                super.getTableCellRendererComponent(t, v, sel, foc, row, col);
                String s = v == null ? "" : v.toString();
                switch (s) {
                    case "Assigned": setForeground(new java.awt.Color(30, 58, 110));  break;
                    case "Pending":  setForeground(new java.awt.Color(160, 90, 0));   break;
                    default:         setForeground(java.awt.Color.DARK_GRAY);
                }
                setFont(getFont().deriveFont(java.awt.Font.BOLD));
                return this;
            }
        });
 
        // Highlight today's rows in light yellow
        tblSchedule.setDefaultRenderer(Object.class,
                new javax.swing.table.DefaultTableCellRenderer() {
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable t, Object v,
                    boolean sel, boolean foc, int row, int col) {
                super.getTableCellRendererComponent(t, v, sel, foc, row, col);
                String today = LocalDate.now()
                        .format(DateTimeFormatter.ofPattern("yyyy-MM-dd"));
                String rowDate = tableModel.getValueAt(row, 0) != null
                        ? tableModel.getValueAt(row, 0).toString() : "";
                if (!sel && rowDate.equals(today)) {
                    setBackground(new java.awt.Color(255, 252, 220));
                } else if (!sel) {
                    setBackground(java.awt.Color.WHITE);
                }
                // Re-apply status colour for col 7
                if (col == 7) {
                    String s = v == null ? "" : v.toString();
                    switch (s) {
                        case "Assigned": setForeground(new java.awt.Color(30, 58, 110));  break;
                        case "Pending":  setForeground(new java.awt.Color(160, 90, 0));   break;
                        default:         setForeground(java.awt.Color.DARK_GRAY);
                    }
                    setFont(getFont().deriveFont(java.awt.Font.BOLD));
                } else {
                    setForeground(java.awt.Color.DARK_GRAY);
                    setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
                }
                return this;
            }
        });
    }
 
    private void loadSchedule() {
        tableModel.setRowCount(0);
        Map<String, String> svcNames = svc.buildServiceNameMap();
        List<Appointment> upcoming   = svc.getUpcomingSchedule();
        String today = LocalDate.now()
                .format(DateTimeFormatter.ofPattern("yyyy-MM-dd"));
 
        for (Appointment a : upcoming) {
            // Get customer info
            Customer cust     = svc.getCustomerById(a.getCustomerId());
            String custName   = cust != null ? cust.getName()  : a.getCustomerId();
            String custPhone  = cust != null ? cust.getPhone() : "-";
 
            // Get service duration
            Service svcInfo   = svc.getServiceInfo(a.getServiceId());
            String duration   = svcInfo != null ? svcInfo.getDurationHours() + " hr(s)" : "-";
 
            // Get day name from date
            String dayName    = svc.getDayName(a.getAppointmentDate());
            String svcName    = svcNames.getOrDefault(a.getServiceId(), a.getServiceId());
 
            tableModel.addRow(new Object[]{
                a.getAppointmentDate(),
                dayName,
                a.getAppointmentTime(),
                svcName,
                duration,
                custName,
                custPhone,
                a.getStatus()
            });
        }
 
        // Update info bar
        int todayHours   = svc.getTotalHoursForDate(today);
        int totalUpcoming = upcoming.size();
        int assignedCount = (int) upcoming.stream()
                .filter(a -> a.getStatus().equalsIgnoreCase("Assigned")).count();
        int pendingCount  = (int) upcoming.stream()
                .filter(a -> a.getStatus().equalsIgnoreCase("Pending")).count();
 
        lblTodayInfo.setText(
                "Today: " + today + "   |   Today's workload: " + todayHours + " hr(s)");
        lblSummary.setText(
                "Total upcoming: " + totalUpcoming
                + "   |   Assigned: " + assignedCount
                + "   |   Pending: " + pendingCount);
    }
 
    


    private void loadComments(String apptId) {
        commentsListPanel.removeAll();
 
        List<Comment> comments = (apptId != null && !apptId.isBlank())
                ? svc.getCommentsForAppointment(apptId)
                : svc.getMyComments();
 
        if (comments.isEmpty()) {
            javax.swing.JLabel empty = new javax.swing.JLabel("  No comments found.");
            empty.setFont(empty.getFont().deriveFont(java.awt.Font.ITALIC));
            empty.setForeground(java.awt.Color.GRAY);
            commentsListPanel.add(empty);
        } else {
            for (Comment c : comments) {
                commentsListPanel.add(buildCommentCard(c));
                commentsListPanel.add(javax.swing.Box.createRigidArea(
                        new java.awt.Dimension(0, 6)));
            }
        }
 
        commentsListPanel.revalidate();
        commentsListPanel.repaint();
    }
 
    private javax.swing.JPanel buildCommentCard(Comment c) {
        javax.swing.JPanel card = new javax.swing.JPanel(new java.awt.BorderLayout(4, 2));
        card.setBackground(java.awt.Color.WHITE);
        card.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                javax.swing.BorderFactory.createMatteBorder(0, 3, 0, 0,
                        new java.awt.Color(30, 58, 110)),
                new javax.swing.border.EmptyBorder(6, 8, 6, 8)));
        card.setMaximumSize(new java.awt.Dimension(Integer.MAX_VALUE, 65));
 
        javax.swing.JLabel meta = new javax.swing.JLabel(
                "Appt: " + c.getAppointmentId() + "   |   From Customer: " + c.getCustomerId());
        meta.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 11));
        meta.setForeground(new java.awt.Color(30, 58, 110));
        card.add(meta, java.awt.BorderLayout.NORTH);
 
        javax.swing.JTextArea text = new javax.swing.JTextArea(c.getCommentText());
        text.setEditable(false);
        text.setLineWrap(true);
        text.setWrapStyleWord(true);
        text.setOpaque(false);
        text.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 12));
        card.add(text, java.awt.BorderLayout.CENTER);
 
        return card;
    }


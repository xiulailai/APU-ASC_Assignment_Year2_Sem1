    private void btnAssignActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAssignActionPerformed
        // TODO add your handling code here:
        if (availableTechnicians.isEmpty()) {
            lblMessage.setForeground(new java.awt.Color(200, 0, 0));
            lblMessage.setText("No technicians available for this slot.");
            return;
        }
 
        Technician selected = availableTechnicians.get(cbTechnician.getSelectedIndex());
        String result = service.assignAppointment(appointmentId, selected.getTechnicianId());
 
        if (result.startsWith("OK:")) {
            lblMessage.setForeground(new java.awt.Color(0, 150, 0));
            lblMessage.setText(result.substring(4));
            parentFrame.refreshTable();
        } else {
            lblMessage.setForeground(new java.awt.Color(200, 0, 0));
            lblMessage.setText(result.substring(5));
        }
    }//GEN-LAST:event_btnAssignActionPerformed


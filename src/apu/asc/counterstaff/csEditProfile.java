    private void loadProfile() {
        CounterStaff cs = service.getProfile(counterStaffId);
        if (cs != null) {
            tfName.setText(cs.getName());
            cbGender.setSelectedItem(cs.getGender());
            tfAge.setText(String.valueOf(cs.getAge()));
            tfPhone.setText(cs.getPhone());
            tfEmail.setText(cs.getEmail());
            tfAddress.setText(cs.getAddress());
            tfNationality.setText(cs.getNationality());
            lblMessage.setText(" ");
        } else {
            lblMessage.setText("Error: Could not load profile.");
        }
    }


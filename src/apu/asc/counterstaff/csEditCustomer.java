    private void loadProfile() {
        Customer c = service.getCustomerById(customerId);
        if (c != null) {
            tfName.setText(c.getName());
            cbGender.setSelectedItem(c.getGender());
            tfAge.setText(String.valueOf(c.getAge()));
            tfPhone.setText(c.getPhone());
            tfEmail.setText(c.getEmail());
            tfAddress.setText(c.getAddress());
            tfNationality.setText(c.getNationality());
            lblMessage.setText(" ");
        } else {
            lblMessage.setForeground(new java.awt.Color(200, 0, 0));
            lblMessage.setText("Error: Customer not found.");
        }
    }


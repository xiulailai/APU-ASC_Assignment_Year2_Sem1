    private void loadTable(List<Customer> customers) {
        DefaultTableModel model = (DefaultTableModel) tblCustomers.getModel();
        model.setRowCount(0); // clear existing rows
        for (Customer c : customers) {
            model.addRow(new Object[]{
                c.getCustomerId(),
                c.getName(),
                c.getGender(),
                c.getAge(),
                c.getPhone(),
                c.getEmail()
            });
        }
    }
    
    private String getSelectedCustomerId() {
        int row = tblCustomers.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please select a customer from the table first.",
                    "No Selection", javax.swing.JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return tblCustomers.getValueAt(row, 0).toString();
    }
    
    public void refreshTable() {
        loadTable(service.getAllCustomers());
    }


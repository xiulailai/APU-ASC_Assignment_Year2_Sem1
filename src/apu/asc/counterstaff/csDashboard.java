    private void loadWelcomeMessage() {
        CounterStaff cs = service.findCounterStaffById(counterStaffId);
        if (cs != null) {
            lblWelcome.setText("Welcome, " + cs.getName() + " (" + counterStaffId + ")");
        } else {
            lblWelcome.setText("Welcome, " + counterStaffId);
        }
    }

